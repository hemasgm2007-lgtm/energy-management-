import { useEffect, useState } from "react";
import {
  Bell,
  AlertTriangle,
  CheckCircle,
  Zap,
  RefreshCw,
} from "lucide-react";

import "../styles/Alerts.css";

const API_URL = "http://127.0.0.1:8000";

function Alerts() {
  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const fetchAlerts = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await fetch(`${API_URL}/alerts/`);

      if (!response.ok) {
        throw new Error("Unable to fetch alerts");
      }

      const result = await response.json();

      const alertData = Array.isArray(result)
        ? result
        : result.data || [];

      setAlerts(alertData);
    } catch (err) {
      console.error("Alerts API error:", err);
      setError("Unable to connect to the FastAPI backend.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, []);

  const activeAlerts = alerts.filter(
    (alert) =>
      alert.is_resolved === false ||
      alert.status?.toLowerCase() === "active" ||
      alert.status?.toLowerCase() === "unresolved"
  ).length;

  const resolvedAlerts = alerts.filter(
    (alert) =>
      alert.is_resolved === true ||
      alert.status?.toLowerCase() === "resolved"
  ).length;

  return (
    <div className="alerts-page">

      {/* HEADER */}
      <div className="alerts-header">

        <div className="alerts-title">

          <div className="alerts-title-icon">
            <Bell size={23} />
          </div>

          <div>
            <h1>Alerts</h1>

            <p>
              Monitor energy consumption warnings and system events
            </p>
          </div>

        </div>

        <button
          className="alerts-refresh"
          onClick={fetchAlerts}
        >
          <RefreshCw size={16} />
          Refresh
        </button>

      </div>


      {/* SUMMARY CARDS */}
      <div className="alerts-stats">

        <div className="alert-stat-card">

          <div className="alert-stat-icon red">
            <AlertTriangle size={21} />
          </div>

          <div>
            <span>Total Alerts</span>
            <strong>{alerts.length}</strong>
          </div>

        </div>


        <div className="alert-stat-card">

          <div className="alert-stat-icon orange">
            <Zap size={21} />
          </div>

          <div>
            <span>Active Alerts</span>
            <strong>{activeAlerts}</strong>
          </div>

        </div>


        <div className="alert-stat-card">

          <div className="alert-stat-icon green">
            <CheckCircle size={21} />
          </div>

          <div>
            <span>Resolved</span>
            <strong>{resolvedAlerts}</strong>
          </div>

        </div>


        <div className="alert-stat-card">

          <div className="alert-stat-icon blue">
            <Bell size={21} />
          </div>

          <div>
            <span>Monitoring</span>
            <strong>Live</strong>
          </div>

        </div>

      </div>


      {/* ALERT PANEL */}
      <div className="alerts-panel">

        <div className="alerts-panel-header">

          <div>
            <h2>Alert History</h2>

            <p>
              Energy monitoring alerts generated by the system
            </p>
          </div>

          <span className="alert-live-badge">
            ● Live
          </span>

        </div>


        {loading ? (

          <div className="alerts-message">
            Loading alerts...
          </div>

        ) : error ? (

          <div className="alerts-message error">
            {error}
          </div>

        ) : alerts.length === 0 ? (

          <div className="alerts-empty">

            <CheckCircle size={42} />

            <h3>No alerts detected</h3>

            <p>
              Your energy monitoring system currently has no alerts.
            </p>

          </div>

        ) : (

          <div className="alert-list">

            {alerts.map((alert, index) => {

              const resolved =
                alert.is_resolved === true ||
                alert.status?.toLowerCase() === "resolved";

              return (
                <div
                  className={`alert-row ${
                    resolved ? "resolved" : "active-alert"
                  }`}
                  key={alert.id || index}
                >

                  <div className="alert-icon">

                    {resolved ? (
                      <CheckCircle size={21} />
                    ) : (
                      <AlertTriangle size={21} />
                    )}

                  </div>


                  <div className="alert-main">

                    <strong>
                      {alert.alert_type ||
                        alert.type ||
                        "Energy Alert"}
                    </strong>

                    <p>
                      {alert.message ||
                        "Energy monitoring threshold exceeded."}
                    </p>

                  </div>


                  <div className="alert-power">

                    <span>Power</span>

                    <strong>
                      {alert.power_kw ?? 0} kW
                    </strong>

                  </div>


                  <div className="alert-threshold">

                    <span>Threshold</span>

                    <strong>
                      {alert.threshold_kw ?? 0} kW
                    </strong>

                  </div>


                  <div className="alert-status">

                    <span
                      className={
                        resolved
                          ? "resolved-badge"
                          : "active-badge"
                      }
                    >
                      ● {resolved ? "Resolved" : "Active"}
                    </span>

                  </div>

                </div>
              );
            })}

          </div>

        )}

      </div>

    </div>
  );
}

export default Alerts;